#!/usr/bin/env bash
# update-cloudflare-ips.sh [--output FILE] [--no-reload] [--dry-run]
#
# Refreshes the list of Cloudflare networks Apache trusts for CF-Connecting-IP (RemoteIPTrustedProxyList in
# deploy/apache/api.bitosx.se.conf). Fetches https://www.cloudflare.com/ips-v4 and /ips-v6, validates every line as
# an IPv4 or IPv6 CIDR, writes the file atomically, runs `apachectl -t` and reloads Apache. On ANY failure (fetch,
# validation, a suspiciously short list, a failing config test) the previous file stays in place and Apache is not
# reloaded. Run it from a timer (e.g. weekly) as root.
#
#   --output FILE   target file (default /etc/apache2/cloudflare-trusted-proxies.conf)
#   --no-reload     validate and install, run `apachectl -t`, but do not reload Apache
#   --dry-run       fetch and validate only; print the list, change nothing
#
# Environment: APACHECTL (default apachectl), BITOSX_CF_IPS_BASE_URL (default https://www.cloudflare.com).
set -euo pipefail

output="/etc/apache2/cloudflare-trusted-proxies.conf"
reload=1
dry_run=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --output)
            [[ $# -ge 2 ]] || { echo "update-cloudflare-ips: --output needs a file" >&2; exit 2; }
            output="$2"
            shift 2
            ;;
        --no-reload) reload=0; shift ;;
        --dry-run) dry_run=1; shift ;;
        *) echo "usage: update-cloudflare-ips.sh [--output FILE] [--no-reload] [--dry-run]" >&2; exit 2 ;;
    esac
done

apachectl_cmd="${APACHECTL:-apachectl}"
base_url="${BITOSX_CF_IPS_BASE_URL:-https://www.cloudflare.com}"
min_v4=5
min_v6=3

log() { printf 'update-cloudflare-ips: %s\n' "$*" >&2; }
die() { printf 'update-cloudflare-ips: error: %s (the previous list is unchanged)\n' "$*" >&2; exit 1; }

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT

fetch() {
    curl -fsS --proto '=https' --tlsv1.2 --max-time 20 --retry 3 --retry-delay 2 -o "$2" "${base_url}/$1" \
        || die "could not fetch ${base_url}/$1"
}

valid_ipv4_cidr() {
    local cidr="$1" address prefix octet
    [[ "${cidr}" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$ ]] || return 1
    address="${cidr%/*}"
    prefix="${cidr#*/}"
    ((10#${prefix} >= 8 && 10#${prefix} <= 32)) || return 1
    IFS=. read -r -a octets <<<"${address}"
    for octet in "${octets[@]}"; do
        ((10#${octet} <= 255)) || return 1
    done
}

valid_ipv6_cidr() {
    local cidr="$1" address prefix colons
    [[ "${cidr}" =~ ^[0-9A-Fa-f:]+/[0-9]{1,3}$ ]] || return 1
    address="${cidr%/*}"
    prefix="${cidr#*/}"
    ((10#${prefix} >= 16 && 10#${prefix} <= 128)) || return 1
    colons="${address//[^:]/}"
    # Either the full eight groups (seven colons) or a compressed form with exactly one "::".
    if [[ "${address}" == *::* ]]; then
        [[ "${address}" != *::*::* && ${#colons} -le 7 ]] || return 1
    else
        [[ ${#colons} -eq 7 ]] || return 1
    fi
    [[ "${address}" != *:::* ]] || return 1
    # Every group has 1..4 hex digits.
    local group
    IFS=: read -r -a groups <<<"${address}"
    for group in "${groups[@]}"; do
        [[ -z "${group}" || "${group}" =~ ^[0-9A-Fa-f]{1,4}$ ]] || return 1
    done
}

# collect <raw-file> <validator> <minimum>: prints the validated CIDRs; dies on any invalid line or a short list.
collect() {
    local raw="$1" validator="$2" minimum="$3" line count=0 name
    name="$(basename "${raw}")"
    while IFS= read -r line || [[ -n "${line}" ]]; do
        line="${line%$'\r'}"
        line="${line#"${line%%[![:space:]]*}"}"
        line="${line%"${line##*[![:space:]]}"}"
        [[ -z "${line}" ]] && continue
        "${validator}" "${line}" || die "invalid entry '${line}' in ${name}"
        printf '%s\n' "${line}"
        count=$((count + 1))
    done <"${raw}"
    ((count >= minimum)) || die "only ${count} entries in ${name} (expected at least ${minimum})"
}

fetch ips-v4 "${work}/ips-v4"
fetch ips-v6 "${work}/ips-v6"
collect "${work}/ips-v4" valid_ipv4_cidr "${min_v4}" >"${work}/v4"
collect "${work}/ips-v6" valid_ipv6_cidr "${min_v6}" >"${work}/v6"

{
    echo "# Cloudflare networks trusted for CF-Connecting-IP (RemoteIPTrustedProxyList)."
    echo "# Generated by deploy/scripts/update-cloudflare-ips.sh from ${base_url}/ips-v4 and /ips-v6. Do not edit."
    cat "${work}/v4" "${work}/v6"
} >"${work}/list"

log "fetched $(wc -l <"${work}/v4") IPv4 and $(wc -l <"${work}/v6") IPv6 networks"
if [[ "${dry_run}" == "1" ]]; then
    cat "${work}/list"
    exit 0
fi

if [[ -f "${output}" ]] && cmp -s <(grep -v '^#' "${output}") <(grep -v '^#' "${work}/list"); then
    log "${output} is already up to date"
    exit 0
fi

dir="$(dirname "${output}")"
[[ -d "${dir}" && -w "${dir}" ]] || die "cannot write to ${dir}"
tmp="$(mktemp "${dir}/.cloudflare-trusted-proxies.XXXXXX")"
previous=""
restore() {
    if [[ -n "${previous}" ]]; then
        mv -f "${previous}" "${output}"
    else
        rm -f "${output}"
    fi
}
cat "${work}/list" >"${tmp}"
chmod 0644 "${tmp}"
if [[ -f "${output}" ]]; then
    previous="$(mktemp "${dir}/.cloudflare-trusted-proxies.previous.XXXXXX")"
    cp -p "${output}" "${previous}"
fi
mv -f "${tmp}" "${output}"

if ! "${apachectl_cmd}" -t >"${work}/configtest" 2>&1; then
    restore
    cat "${work}/configtest" >&2
    die "apachectl -t failed with the new list; restored the previous file"
fi
[[ -n "${previous}" ]] && rm -f "${previous}"
log "installed ${output}"

if [[ "${reload}" == "1" ]]; then
    if ! "${apachectl_cmd}" graceful; then
        log "error: apachectl graceful failed; the new list is installed and passed apachectl -t"
        exit 1
    fi
    log "Apache reloaded"
fi
